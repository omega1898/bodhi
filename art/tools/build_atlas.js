// Purpose: the art pipeline. Opens each painted character sheet (an SVG file in
// art/characters/), finds every part (a group named part_*), measures where it sits on the
// sheet and where its joint is, and writes prototype/web/js/art_atlas.js. The game uses that
// map to cut each part out of the sheet and rotate it around its joint.
// Run it after editing any character art:
//   node art/tools/build_atlas.js
'use strict';

const path = require('path');
const fs = require('fs');
const { chromium } = require('playwright');

const repository_root = path.resolve(__dirname, '..', '..');
const sheets = { her: 'art/characters/her.svg', bodhi: 'art/characters/bodhi.svg' };
const padding = 28;  // Room around each part for soft filter edges (fur, grain).
const output_path = path.join(repository_root, 'prototype', 'web', 'js', 'art_atlas.js');

// Measures every part on one sheet inside a real browser, which understands SVG exactly.
async function measure_sheet(page, sheet_path) {
    await page.goto('file://' + path.join(repository_root, sheet_path));
    return page.evaluate((pad) => {
        const svg = document.querySelector('svg');
        const parts = {};
        for (const group of svg.querySelectorAll('g[id^="part_"]')) {
            const match = /translate\(\s*([-\d.]+)[ ,]+([-\d.]+)\s*\)/.exec(group.getAttribute('transform') || '');
            const joint_x = match ? Number(match[1]) : 0;
            const joint_y = match ? Number(match[2]) : 0;
            const box = group.getBBox();  // In the part's own coordinates, around its joint.
            const left = Math.floor(joint_x + box.x - pad);
            const top = Math.floor(joint_y + box.y - pad);
            const width = Math.ceil(box.width + pad * 2);
            const height = Math.ceil(box.height + pad * 2);
            parts[group.id.replace('part_', '')] = { x: left, y: top, w: width, h: height, joint_x: joint_x - left, joint_y: joint_y - top };
        }
        return { width: Number(svg.getAttribute('width')), height: Number(svg.getAttribute('height')), parts: parts };
    }, padding);
}

async function main() {
    const browser = await chromium.launch();
    const page = await browser.newPage();
    const atlas = {};
    for (const [name, sheet_path] of Object.entries(sheets)) {
        const measured = await measure_sheet(page, sheet_path);
        // Two parts whose cut-out areas overlap would each carry a sliver of the other into the
        // game. Refuse the sheet and say which parts to move apart.
        const entries = Object.entries(measured.parts);
        for (let first = 0; first < entries.length; first++) {
            for (let second = first + 1; second < entries.length; second++) {
                const a = entries[first][1];
                const b = entries[second][1];
                if (a.x < b.x + b.w && a.x + a.w > b.x && a.y < b.y + b.h && a.y + a.h > b.y) {
                    console.error('OVERLAP on ' + sheet_path + ': ' + entries[first][0] + ' and ' + entries[second][0] + ' are too close. Move them apart.');
                    process.exitCode = 1;
                }
            }
            const part = entries[first][1];
            if (part.x < 0 || part.y < 0 || part.x + part.w > measured.width || part.y + part.h > measured.height) {
                console.error('EDGE on ' + sheet_path + ': ' + entries[first][0] + ' runs off the sheet. Move it inward.');
                process.exitCode = 1;
            }
        }
        atlas[name] = Object.assign({ sheet: sheet_path }, measured);
        console.log(name + ': ' + Object.keys(measured.parts).join(', '));
    }
    await browser.close();
    const header = [
        '// Purpose: where each painted body part sits on its character sheet, and where its joint is.',
        '// Generated by art/tools/build_atlas.js from the SVG files in art/characters/. Do not edit',
        '// by hand: edit the art, then run  node art/tools/build_atlas.js',
        "'use strict';",
        '',
    ].join('\n');
    if (process.exitCode) {
        console.error('atlas NOT written: fix the sheets above first');
        return;
    }
    fs.writeFileSync(output_path, header + 'const art_atlas = ' + JSON.stringify(atlas, null, 4) + ';\n');
    console.log('wrote ' + path.relative(repository_root, output_path));
}

main();
